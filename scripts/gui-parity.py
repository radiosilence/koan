#!/usr/bin/env python3
"""The parity inventory: what the SwiftUI app has, for koan-gui to match.

Reads the Mac app's sources (apps/macos/Sources/Koan, the views and models
the Mac and iOS share; iOS- and tvOS-only files are left out) and lists, per
file, every view, button and menu action, toggle, tooltip, keyboard shortcut,
empty state and accessibility label, as a markdown checklist on stdout.

An item is ticked when its text, lowercased and without its ellipsis, appears
in koan-gui's or koan-kit's sources, which kōan draws lowercase. That is a
first pass and no more: a tick says the words are there, not that the
behaviour matches, and an unticked item may be done under other words. The
checklist on #1625 is ticked by hand from there.

    python3 scripts/gui-parity.py > target/gui-parity.md
    python3 scripts/gui-parity.py --summary
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWIFT = ROOT / "apps/macos/Sources/Koan"
RUST = [ROOT / "crates/koan-gui/src", ROOT / "crates/koan-kit/src"]

STRING = r'"((?:[^"\\]|\\.)+)"'
KINDS = [
    ("view", re.compile(r"^\s*(?:private |fileprivate )?struct (\w+)\s*:\s*View\b", re.M)),
    ("action", re.compile(r"\bButton\(\s*" + STRING)),
    ("action", re.compile(r"\bLabel\(\s*" + STRING)),
    ("setting", re.compile(r"\bToggle\(\s*" + STRING)),
    ("setting", re.compile(r"\bPicker\(\s*" + STRING)),
    ("tooltip", re.compile(r"\.help\(\s*" + STRING)),
    ("shortcut", re.compile(r"\.keyboardShortcut\(([^)]*)\)")),
    ("empty state", re.compile(r"\bKoanUnavailable\(\s*" + STRING)),
    ("accessibility", re.compile(r"\.accessibilityLabel\(\s*" + STRING)),
]


def rust_text() -> str:
    parts = []
    for root in RUST:
        for path in root.rglob("*.rs"):
            parts.append(path.read_text(errors="ignore").lower())
    return "\n".join(parts)


def plain(text: str) -> str:
    """A label as koan-gui would write it: lowercase, no ellipsis, no
    interpolation."""
    text = re.sub(r"\\\(.*?\)", "", text)
    return text.replace("…", "").replace("...", "").strip().lower()


def shared(path: Path, source: str) -> bool:
    """A file the Mac app compiles: not one wholly for iOS or tvOS."""
    head = source.lstrip()
    return not (head.startswith("#if os(iOS)") or head.startswith("#if os(tvOS)"))


def inventory():
    rust = rust_text()
    files = []
    for path in sorted(SWIFT.rglob("*.swift")):
        source = path.read_text(errors="ignore")
        if not shared(path, source):
            continue
        items, seen = [], set()
        for kind, pattern in KINDS:
            for match in pattern.finditer(source):
                text = match.group(1).strip()
                key = (kind, text)
                if not text or key in seen:
                    continue
                seen.add(key)
                words = plain(text)
                done = kind != "shortcut" and kind != "view" and len(words) > 2 and words in rust
                items.append((kind, text, done))
        if items:
            files.append((path.relative_to(ROOT), items))
    return files


def main():
    files = inventory()
    total = sum(len(items) for _, items in files)
    ticked = sum(done for _, items in files for _, _, done in items)
    if "--summary" in sys.argv:
        print(f"{total} items in {len(files)} files, {ticked} found in koan-gui by their words")
        return
    print("## Parity inventory\n")
    print(
        f"Generated by `scripts/gui-parity.py` from `apps/macos/Sources/Koan`: "
        f"{total} items in {len(files)} files. A tick means the item's words appear "
        f"in koan-gui or koan-kit ({ticked} so far); tick the rest by hand as they "
        f"are matched or bettered.\n"
    )
    for path, items in files:
        print(f"<details><summary><code>{path}</code> ({sum(d for *_, d in items)}/{len(items)})</summary>\n")
        for kind, text, done in items:
            print(f"- [{'x' if done else ' '}] {kind}: {text}")
        print("\n</details>\n")


if __name__ == "__main__":
    main()
