#!/usr/bin/env python3
"""Compile the kōan icon set for Android.

Reads every SVG in apps/macos/Resources/Icons, through the parser that
scripts/icons.py compiles the Swift set with, and writes:

- one vector drawable per glyph, `res/drawable/koan_<name>.xml`, its paths
  named `stroke` or `fill` by the layer they belong to;
- `ui/theme/KoanIcons.kt`, the names of `Icon` in the Swift apps
  (Support/Icons.swift), each mapped to its glyph's drawable, so both apps
  ask for an icon by the same name.

The drawables carry the source's 1.5-unit stroke, which is what they show
where Android draws them itself (notifications, the media session). `KoanIcon`
redraws their paths with the width the size calls for (`KoanGlyph.strokeWidth`).

With --check, writes nothing and fails if any output is stale.

Usage: apps/android/scripts/icons.py [--check]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))

from icons import ICONS, SOURCES, load  # noqa: E402

APP = ROOT / "apps/android/app/src/main"
DRAWABLES = APP / "res/drawable"
KOTLIN = APP / "kotlin/cc/blit/koan/ui/theme/KoanIcons.kt"
STROKE = 1.5
HEADER = "Generated by apps/android/scripts/icons.py from apps/macos/Resources/Icons. Edit the SVGs, not this file."


def resource(name):
    return "koan_" + name.replace("-", "_")


def drawable(strokes, fills):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {HEADER} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24">',
    ]
    if fills:
        lines += [
            "    <path",
            '        android:name="fill"',
            f'        android:pathData="{fills}"',
            '        android:fillColor="#FFFFFFFF"',
            '        android:strokeColor="#FFFFFFFF"',
            f'        android:strokeWidth="{STROKE}"',
            '        android:strokeLineCap="square"',
            '        android:strokeLineJoin="miter" />',
        ]
    if strokes:
        lines += [
            "    <path",
            '        android:name="stroke"',
            f'        android:pathData="{strokes}"',
            '        android:strokeColor="#FFFFFFFF"',
            f'        android:strokeWidth="{STROKE}"',
            '        android:strokeLineCap="square"',
            '        android:strokeLineJoin="miter" />',
        ]
    lines += ["</vector>", ""]
    return "\n".join(lines)


def icons_kotlin(glyphs):
    by_symbol = {symbol: name for name, symbols, _, _ in glyphs for symbol in symbols}
    lines = [
        f"// {HEADER}",
        "",
        "package cc.blit.koan.ui.theme",
        "",
        "import cc.blit.koan.R",
        "",
        "/**",
        " * The app's icons, by what they stand for: the names the Swift apps give them",
        " * (`Icon` in Support/Icons.swift), each the drawable of its kōan glyph. Draw",
        " * one with `KoanIcon`.",
        " */",
        "object KoanIcons {",
    ]
    for role, symbol in re.findall(r'static let (\w+) = "([^"]+)"', ICONS.read_text()):
        if symbol in by_symbol:
            lines.append(f"    val {role} = R.drawable.{resource(by_symbol[symbol])}")
    lines += ["", "    /** Every glyph in the set, by its source's name, for the theme sheet. */", "    val all = listOf("]
    lines += [f'        "{name}" to R.drawable.{resource(name)},' for name, _, _, _ in glyphs]
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def main():
    glyphs = [load(path) for path in sorted(SOURCES.glob("*.svg"))]
    outputs = {DRAWABLES / f"{resource(name)}.xml": drawable(strokes, fills) for name, _, strokes, fills in glyphs}
    outputs[KOTLIN] = icons_kotlin(glyphs)
    stale_drawables = {p for p in DRAWABLES.glob("koan_*.xml")} - set(outputs)

    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text] + sorted(stale_drawables)
        if stale:
            sys.exit(f"{len(stale)} icon outputs are stale: run apps/android/scripts/icons.py")
        return
    for path, text in outputs.items():
        path.write_text(text)
    for path in stale_drawables:
        path.unlink()
    print(f"{len(glyphs)} glyphs → {DRAWABLES.relative_to(ROOT)}, {KOTLIN.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
