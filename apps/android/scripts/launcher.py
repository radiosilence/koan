#!/usr/bin/env python3
"""Draw the Android app's launcher and notification icons from the kōan ensō.

Reads the ensō stroke and the tile colour from apps/macos/Resources/AppIcon.svg,
the Apple apps' icon, and writes:

- the adaptive launcher icon (`mipmap-anydpi/ic_launcher.xml`): the tile colour
  behind, the ensō with its glow in front, and the ensō alone as the monochrome
  layer for themed icons. The icon's 512 units span the 72 dp the launcher
  shows of the 108-dp layers, so the ensō sits in it as on the Apple icon;
- `drawable/ic_notification.xml`, the ensō alone, white, filling the status
  bar's 24-dp square, for the media notification;
- `drawable/koan_enso.xml`, the placeholder for a record without a cover:
  the ensō alone, white for the app to tint, in the middle of a square it
  fills, as the Apple apps' `EnsoPlaceholder` draws it.

Usage: apps/android/scripts/launcher.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "apps/macos/Resources/AppIcon.svg"
RES = ROOT / "apps/android/app/src/main/res"
HEADER = "<!-- Generated by apps/android/scripts/launcher.py from apps/macos/Resources/AppIcon.svg. -->"

svg = SOURCE.read_text()
tile = re.search(r'<rect[^>]*fill="(#[0-9A-Fa-f]{6})"', svg).group(1)
strokes = re.findall(r'<path d="([^"]*)"\s+fill="none"([^>]*)>', svg)
glow = (next(d for d, attrs in strokes if "opacity" in attrs))
enso = (next(d for d, attrs in strokes if "opacity" not in attrs))
ink = re.search(r'stroke="(#[0-9A-Fa-f]{6})"', svg).group(1)
glow_width = re.search(r'stroke-width="(\d+)"', next(a for d, a in strokes if "opacity" in a)).group(1)
enso_width = re.search(r'stroke-width="(\d+)"', next(a for d, a in strokes if "opacity" not in a)).group(1)


def path(d, colour, width, alpha=None):
    lines = [
        "        <path",
        f'            android:pathData="{d}"',
        f'            android:strokeColor="{colour}"',
        f'            android:strokeWidth="{width}"',
        '            android:strokeLineCap="round"',
        '            android:strokeLineJoin="round"',
    ]
    if alpha:
        lines.append(f'            android:strokeAlpha="{alpha}"')
    lines[-1] += " />"
    return lines


def vector(size, viewport, scale, translate, paths):
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            HEADER,
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    xmlns:tools="http://schemas.android.com/tools"',
            # The ensō keeps the source's point every two units: simplified
            # enough for lint, it turns polygonal. Launchers and the status bar
            # draw it once and keep the bitmap.
            '    tools:ignore="VectorPath"',
            f'    android:width="{size}dp"',
            f'    android:height="{size}dp"',
            f'    android:viewportWidth="{viewport}"',
            f'    android:viewportHeight="{viewport}">',
            "    <group",
            f'        android:scaleX="{scale:.6f}"',
            f'        android:scaleY="{scale:.6f}"',
            f'        android:translateX="{translate[0]:.3f}"',
            f'        android:translateY="{translate[1]:.3f}">',
            *paths,
            "    </group>",
            "</vector>",
            "",
        ]
    )


def bounds(d):
    values = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", d)]
    xs, ys = values[::2], values[1::2]
    return min(xs), min(ys), max(xs), max(ys)


outputs = {}
# The layers are 108 dp; the launcher shows the middle 72.
layer_scale = 72 / 512
outputs["drawable/ic_launcher_foreground.xml"] = vector(
    108, 108, layer_scale, (18, 18),
    path(glow, ink, glow_width, "0.22") + path(enso, ink, enso_width),
)
outputs["drawable/ic_launcher_monochrome.xml"] = vector(
    108, 108, layer_scale, (18, 18), path(enso, "#FFFFFFFF", enso_width),
)
outputs["values/ic_launcher_background.xml"] = "\n".join(
    [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER,
        "<resources>",
        f'    <color name="ic_launcher_background">{tile}</color>',
        "</resources>",
        "",
    ]
)
adaptive = "\n".join(
    [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER,
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
        '    <background android:drawable="@color/ic_launcher_background" />',
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />',
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />',
        "</adaptive-icon>",
        "",
    ]
)
outputs["mipmap-anydpi/ic_launcher.xml"] = adaptive
outputs["mipmap-anydpi/ic_launcher_round.xml"] = adaptive

# The ensō, its stroke included, filling 22 of the notification's 24 dp.
x0, y0, x1, y1 = bounds(enso)
half = int(enso_width) / 2
side = max(x1 - x0, y1 - y0) + 2 * half
scale = 22 / side
cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
outputs["drawable/ic_notification.xml"] = vector(
    24, 24, scale, (12 - cx * scale, 12 - cy * scale), path(enso, "#FFFFFFFF", enso_width),
)

# The Apple apps' placeholder: the icon's 512 units in the middle 48% of the
# sleeve, its stroke 4.5% of the sleeve's side, lighter than the icon's own.
outputs["drawable/koan_enso.xml"] = vector(
    48, 512, 0.48, (0.26 * 512, 0.26 * 512), path(enso, "#FFFFFFFF", f"{0.045 / 0.48 * 512:.0f}"),
)

for name, text in outputs.items():
    target = RES / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(target.relative_to(ROOT))
